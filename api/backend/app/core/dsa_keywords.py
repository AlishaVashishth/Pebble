def has_prompt_injection(text: str) -> bool:
    """Check if the text contains known prompt-injection attempt phrases."""
    normalized = text.lower()
    return any(phrase in normalized for phrase in PROMPT_INJECTION_PHRASES)


def contains_dsa_keyword(text: str) -> bool:
    """Check if the given text contains any known DSA keyword.
    
    Multi-word phrases and hyphenated terms are matched as substrings.
    Single-word tokens and acronyms are matched using word boundaries.
    """
    normalized = text.lower()
    for kw in DSA_KEYWORDS:
        if " " in kw or "-" in kw:
            if kw in normalized:
                return True
        else:
            if re.search(r"\b" + re.escape(kw) + r"(?:s|es)?\b", normalized):
                return True
    return False
